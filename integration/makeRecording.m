function rec = makeRecording(patientId, sessionId, exerciseId, sourceType, fs, channelNames, data)
% MAKERECORDING  The one data format every source must produce.
% Dataset replay, simulated data and (later) a live device all return this
% exact struct, so the dashboard and fusion engine never care where data came from.
%
%   data is channels x samples; fs is the sampling frequency in Hz.
arguments
    patientId (1,1) string
    sessionId (1,1) string
    exerciseId (1,1) string
    sourceType (1,1) string {mustBeMember(sourceType, ["dataset_replay","simulated","live_device"])}
    fs (1,1) double {mustBePositive}
    channelNames (1,:) string
    data (:,:) double
end
assert(size(data,1) == numel(channelNames), ...
    "data must be channels x samples, with one row per channel name.");

rec = struct( ...
    "patient_id",    patientId, ...
    "session_id",    sessionId, ...
    "exercise_id",   exerciseId, ...
    "timestamp",     datetime("now"), ...
    "source_type",   sourceType, ...
    "fs",            fs, ...
    "channel_names", channelNames, ...
    "data",          data);
end
